class PersonalAssistant:
    """
    简单个人助手核心业务类。

    设计原则（Harness Engineering）：
      - 零 I/O 耦合：方法不使用 input()/print()，所有输入通过参数传入，结果通过 return 返回，
        便于测试套件直接对返回值进行 assert 断言。
      - 高内聚低耦合：每个方法只承担单一职责，方法之间互不依赖、互不干扰。
      - 自解释命名：方法名与参数名直接表达业务含义，降低阅读和测试成本。
    """

    # ------------------------------------------------------------------
    # 业务常量集中管理
    # 之所以把阈值抽成类常量，是为了：
    #   1) 让“魔法数字”有明确语义，便于白盒测试覆盖边界值；
    #   2) 后续业务调整阈值时只需改一处，避免逻辑分支与数值耦合。
    # ------------------------------------------------------------------

    # 单笔支出告警上限：5000 元
    # 依据：普通个人日常消费场景中，单笔超过 5000 元已属于“大额支出”，
    # 极可能是误操作或盗刷，需要二次确认以保护用户资金安全。
    MAX_SINGLE_EXPENSE = 5000.0

    # 单笔收入告警上限：10000 元
    # 依据：个人助手面向日常记账，单笔超过 10000 元的收入属于非常规情况
    # （如奖金、转账误录），需提示用户确认，避免错记影响后续统计。
    MAX_SINGLE_INCOME = 10000.0

    # 日记字数下限：10 字
    # 依据：少于 10 字的日记几乎无法承载有效信息，不利于后续回顾。
    MIN_DIARY_LENGTH = 10

    # 日记字数上限：200 字
    # 依据：个人助手场景强调“轻量记录”，超过 200 字会增加用户负担，
    # 也不便于在移动端列表中预览。
    MAX_DIARY_LENGTH = 200

    # 健康饮水基线：2000 毫升
    # 依据：世界卫生组织及多数膳食指南建议成年人每日饮水量约为 2000 毫升。
    HEALTHY_WATER_ML = 2000

    # 饮水预警下限：1000 毫升
    # 依据：低于 1000 毫升通常意味着明显脱水风险，需明确区分“偏少”与“危险”。
    WARNING_WATER_ML = 1000

    # BMI 分级阈值（依据《中国成人超重和肥胖症预防控制指南》）
    # 之所以使用国标而非 WHO 标准，是因为目标用户主要为中国成年人，
    # 国标对超重/肥胖的界定更贴合本地人群体质特征。
    BMI_UNDERWEIGHT_MAX = 18.5   # 低于该值视为偏瘦
    BMI_NORMAL_MAX = 24.0        # [18.5, 24) 为正常体重
    BMI_OVERWEIGHT_MAX = 28.0    # [24, 28) 为超重，>=28 为肥胖

    # 月度预算预警阈值
    # 依据：在个人理财场景中，花费达到预算的 80% 时即应提示节制，
    # 给用户留出调整空间；超过 100% 则属于已经超支，必须强提醒。
    BUDGET_WARNING_RATIO = 0.8
    BUDGET_OVER_RATIO = 1.0

    # 睡眠时长健康区间（小时）
    # 依据：美国国家睡眠基金会建议成年人每日睡眠 7-9 小时，
    # 这里放宽下限至 6 小时以兼顾轻度短睡眠人群的常见情况，
    # 上限 9 小时之外则视为过度睡眠，可能与健康问题相关。
    MIN_HEALTHY_SLEEP = 6.0
    MAX_HEALTHY_SLEEP = 9.0
    MAX_VALID_SLEEP = 24.0       # 一天最多 24 小时，超出即非法输入

    # 最近记录默认条数
    # 依据：在移动端列表展示中，10 条以内可一屏内浏览，
    # 既能满足「快速回顾」需求，又不会因数据过多增加渲染负担。
    DEFAULT_RECENT_COUNT = 10

    # ------------------------------------------------------------------
    # 功能 1：记账助手 - 收支限额检查
    # ------------------------------------------------------------------
    def check_transaction(self, amount: float) -> bool:
        """
        校验单笔交易金额是否处于安全区间。

        :param amount: 单笔交易金额，正数代表收入，负数代表支出。
        :return: True 表示金额正常；False 表示触发大额异常，需要二次确认。
        """
        # 为什么先判断支出分支：
        #   业务约定“负数代表支出”，单笔支出超过 5000 元（即 amount < -5000）
        #   属于资金风险点，需立即拦截以避免误操作或盗刷损失。
        if amount < -self.MAX_SINGLE_EXPENSE:
            return False

        # 为什么单独判断收入分支：
        #   单笔收入超过 10000 元在个人记账场景中属于非常规事件，
        #   错记会显著影响月度/年度统计，必须让用户二次确认。
        if amount > self.MAX_SINGLE_INCOME:
            return False

        # 为什么默认返回 True：
        #   在两个上限之间的金额属于常规收支，无需打扰用户，
        #   保持“最小提示”原则，提升记账效率。
        return True

    # ------------------------------------------------------------------
    # 功能 2：记录生活 - 日记字数规范
    # ------------------------------------------------------------------
    def validate_diary(self, content: str) -> bool:
        """
        校验日记内容长度是否符合规范。

        :param content: 日记原始字符串内容。
        :return: True 表示字数合规；False 表示太短或太长。
        """
        # 为什么先做 strip 再计算长度：
        #   用户输入常携带首尾空格或换行（尤其在移动端键盘），
        #   若不去除会导致“看似有内容、实则为空白”的误判，影响测试可预期性。
        trimmed_content = content.strip()
        content_length = len(trimmed_content)

        # 为什么使用闭区间 [MIN, MAX] 判断：
        #   产品规范明确“含边界”，使用 <= 与 >= 可以精确覆盖边界值，
        #   避免出现“正好 10 字 / 正好 200 字”被误判为不合规的情况，
        #   同时也方便测试套件直接构造边界用例进行断言。
        if self.MIN_DIARY_LENGTH <= content_length <= self.MAX_DIARY_LENGTH:
            return True

        # 为什么不区分“太短”和“太长”分别返回：
        #   本方法职责单一，只负责“是否合规”的布尔判断，
        #   具体提示文案应由上层 UI 层根据返回值组合决定，保持低耦合。
        return False

    # ------------------------------------------------------------------
    # 功能 3：健康助手 - 每日饮水量评标
    # ------------------------------------------------------------------
    def evaluate_water_intake(self, water_ml: int) -> str:
        """
        根据每日饮水量给出健康评级。

        :param water_ml: 每日饮水量，单位毫升。
        :return: "Invalid" / "Healthy" / "Warning" / "Danger" 之一。
        """
        # 为什么最先拦截负数：
        #   饮水量在物理意义上不存在负值，若不优先拦截，
        #   后续区间比较会得出语义错误的结论（例如 -100 会被归为 "Danger"），
        #   单独返回 "Invalid" 可以让上层准确识别为“数据非法”而非“健康危险”。
        if water_ml < 0:
            return "Invalid"

        # 为什么 >= 2000 判定为 Healthy：
        #   2000 毫升是公认的每日基础需水量，达到该值意味着满足基础代谢需求，
        #   使用 >= 保证“恰好 2000”也被认可为健康，符合用户直觉。
        if water_ml >= self.HEALTHY_WATER_ML:
            return "Healthy"

        # 为什么 1000 <= x < 2000 判定为 Warning：
        #   此区间饮水量未达到推荐值但尚未触及严重缺水线，
        #   属于“需要提醒但无须告警”的中间态，给用户一个改善空间。
        if water_ml >= self.WARNING_WATER_ML:
            return "Warning"

        # 为什么 < 1000 判定为 Danger：
        #   低于 1000 毫升时，人体可能出现明显脱水症状（口渴、尿少、乏力），
        #   需要以最高优先级提醒用户立即补水，因此使用最严重的等级。
        return "Danger"

    # ------------------------------------------------------------------
    # 功能 4：健康助手 - BMI 评级
    # ------------------------------------------------------------------
    def evaluate_bmi(self, height_m: float, weight_kg: float) -> str:
        """
        根据身高体重计算 BMI 并给出体型评级。

        :param height_m: 身高，单位米（float）。
        :param weight_kg: 体重，单位公斤（float）。
        :return: "Invalid" / "Underweight" / "Normal" / "Overweight" / "Obese"。
        """
        # 为什么先拦截非正数输入：
        #   身高、体重在物理意义上必须为正数，若不优先拦截会触发
        #   除零异常或得出无意义的负 BMI，单独返回 "Invalid" 可让上层
        #   明确区分“非法输入”与“真实健康风险”。
        if height_m <= 0 or weight_kg <= 0:
            return "Invalid"

        # 为什么把计算单独成行：
        #   将 BMI 公式与分支判断解耦，方便白盒测试通过参数化
        #   直接覆盖各 BMI 边界，也降低后续公式调整的风险。
        bmi = weight_kg / (height_m * height_m)

        # 为什么 < 18.5 判定为 Underweight：
        #   国标界定 BMI<18.5 为体重过低，可能伴随营养不良风险，
        #   需提示用户增加营养摄入。
        if bmi < self.BMI_UNDERWEIGHT_MAX:
            return "Underweight"

        # 为什么 [18.5, 24) 判定为 Normal：
        #   国标推荐的健康区间，无需健康干预，保持现状即可。
        if bmi < self.BMI_NORMAL_MAX:
            return "Normal"

        # 为什么 [24, 28) 判定为 Overweight：
        #   国标超重区间，慢性病风险开始上升，需提醒用户控制饮食、增加运动。
        if bmi < self.BMI_OVERWEIGHT_MAX:
            return "Overweight"

        # 为什么 >= 28 判定为 Obese：
        #   国标肥胖临界点，与高血压、糖尿病等强相关，
        #   需要以最高等级提醒用户关注体重管理。
        return "Obese"

    # ------------------------------------------------------------------
    # 功能 5：记账助手 - 月度预算预警
    # ------------------------------------------------------------------
    def check_monthly_budget(self, spent: float, budget: float) -> str:
        """
        根据本月已花金额与预算的比值给出预算状态。

        :param spent: 本月已花金额。
        :param budget: 本月预算总额，必须为正数。
        :return: "Invalid" / "Safe" / "Warning" / "Over"。
        """
        # 为什么先拦截 budget <= 0：
        #   预算为 0 或负数在业务上无意义，且会触发除零异常，
        #   必须最先短路返回，避免后续比值计算崩溃。
        if budget <= 0:
            return "Invalid"

        # 为什么允许 spent 为负但单独拦截：
        #   spent 为负通常代表“退款金额大于支出”，
        #   在统计上仍可视为安全（甚至更安全），因此不归为 Invalid，
        #   但需要避免负比值参与后续逻辑，统一返回 "Safe"。
        if spent < 0:
            return "Safe"

        # 为什么使用比值而非绝对差额：
        #   不同用户预算量级差异极大（如学生 vs 工薪），
        #   使用比值能让预警阈值在所有用户身上保持业务一致性。
        ratio = spent / budget

        # 为什么 ratio > 1.0 优先判断：
        #   超支是最高优先级风险事件，需要立刻提醒，
        #   优先短路返回可避免被后续 Warning 分支误覆盖。
        if ratio > self.BUDGET_OVER_RATIO:
            return "Over"

        # 为什么 ratio >= 0.8 判定为 Warning：
        #   达到预算 80% 时距离超支只剩一步，
        #   此时提醒用户可以及时调整后续消费计划，避免月末超支。
        if ratio >= self.BUDGET_WARNING_RATIO:
            return "Warning"

        # 为什么默认返回 Safe：
        #   消费在预算 80% 以内属于正常节奏，无需打扰用户，
        #   符合“最小提示”的产品体验原则。
        return "Safe"

    # ------------------------------------------------------------------
    # 功能 6：生活助手 - 睡眠时长评级
    # ------------------------------------------------------------------
    def evaluate_sleep(self, hours: float) -> str:
        """
        根据每日睡眠时长给出健康评级。

        :param hours: 当日睡眠小时数（float）。
        :return: "Invalid" / "Insufficient" / "Healthy" / "Excessive"。
        """
        # 为什么把 [0, 24] 之外的值统一视为非法：
        #   一天物理上不可能超过 24 小时，负数同样不存在，
        #   优先拦截可避免错误数据污染健康评级结果。
        if hours < 0 or hours > self.MAX_VALID_SLEEP:
            return "Invalid"

        # 为什么 < 6 判定为 Insufficient：
        #   长期低于 6 小时睡眠会显著增加心血管和免疫系统风险，
        #   需作为明确预警提示用户调整作息。
        if hours < self.MIN_HEALTHY_SLEEP:
            return "Insufficient"

        # 为什么 [6, 9] 判定为 Healthy：
        #   美国国家睡眠基金会推荐成年人 7-9 小时，
        #   下限放宽至 6 小时以兼顾日常波动，使用闭区间保证 6 和 9 都被认可。
        if hours <= self.MAX_HEALTHY_SLEEP:
            return "Healthy"

        # 为什么 > 9 判定为 Excessive：
        #   长期过量睡眠同样与抑郁、代谢综合征等问题相关，
        #   需要提示用户关注作息规律，而非简单认为「睡得多就好」。
        return "Excessive"

    # ------------------------------------------------------------------
    # 功能 7：通用记录展示 - 获取最近 N 条记录
    # ------------------------------------------------------------------
    def get_recent_records(self, records, n=None):
        """
        从全量记录列表中截取最近 N 条，按时间倒序返回（最新的在前）。

        :param records: 完整记录列表（每条记录为 dict，需包含 "time" 字段，
                        以 ISO 字符串形式存储，便于字典序即时间序）。
        :param n: 期望返回的最大条数；None 时使用类常量 DEFAULT_RECENT_COUNT。
        :return: 一个新的列表，长度 <= n，按时间倒序排列；非法输入返回空列表。
        """
        # 为什么 records 不是 list 时返回空列表：
        #   防御式编程，避免调用方传入 None 或字符串等错误类型时抛异常，
        #   GUI 层在首次启动（records.json 不存在）时也能安全展示「暂无记录」。
        if not isinstance(records, list):
            return []

        # 为什么使用默认条数常量：
        #   当调用方未指定 n 时，使用业务约定的 10 条作为缺省值，
        #   避免重复在 GUI 层各处硬编码「显示多少条」。
        if n is None:
            n = self.DEFAULT_RECENT_COUNT

        # 为什么 n <= 0 时也返回空列表：
        #   语义上「展示 0 条或负数条」等价于「不展示」，
        #   单独短路返回可避免后续切片产生反向截取等意外行为。
        if n <= 0:
            return []

        # 为什么使用 sorted 而非原地 sort：
        #   不修改调用方传入的原始列表，遵循「函数无副作用」原则，
        #   便于测试套件断言「输入列表未被改变」。
        # 为什么 key 用 "time" 字段、reverse=True：
        #   业务上「最近」=「时间最大」，倒序排列让最新记录排在最上方，
        #   符合用户对「时间线」从新到旧的浏览习惯。
        sorted_records = sorted(
            records,
            key=lambda r: r.get("time", ""),
            reverse=True,
        )

        # 为什么使用切片而非循环：
        #   Python 切片对越界自动截断，n 大于列表长度时不会抛异常，
        #   写法简洁且性能优于显式循环。
        return sorted_records[:n]
