class PersonalAssistant:
    """
    简单个人助手核心业务类。

    设计原则（Harness Engineering）：
      - 零 I/O 耦合：方法不使用 input()/print()，所有输入通过参数传入，结果通过 return 返回，
        便于测试套件直接对返回值进行 assert 断言。
      - 高内聚低耦合：每个方法只承担单一职责，方法之间互不依赖、互不干扰。
      - 自解释命名：方法名与参数名直接表达业务含义，降低阅读和测试成本。
    """

    # ------------------------------------------------------------------
    # 业务常量集中管理
    # 之所以把阈值抽成类常量，是为了：
    #   1) 让“魔法数字”有明确语义，便于白盒测试覆盖边界值；
    #   2) 后续业务调整阈值时只需改一处，避免逻辑分支与数值耦合。
    # ------------------------------------------------------------------

    # 单笔支出告警上限：5000 元
    # 依据：普通个人日常消费场景中，单笔超过 5000 元已属于“大额支出”，
    # 极可能是误操作或盗刷，需要二次确认以保护用户资金安全。
    MAX_SINGLE_EXPENSE = 5000.0

    # 单笔收入告警上限：10000 元
    # 依据：个人助手面向日常记账，单笔超过 10000 元的收入属于非常规情况
    # （如奖金、转账误录），需提示用户确认，避免错记影响后续统计。
    MAX_SINGLE_INCOME = 10000.0

    # 日记字数下限：10 字
    # 依据：少于 10 字的日记几乎无法承载有效信息，不利于后续回顾。
    MIN_DIARY_LENGTH = 10

    # 日记字数上限：200 字
    # 依据：个人助手场景强调“轻量记录”，超过 200 字会增加用户负担，
    # 也不便于在移动端列表中预览。
    MAX_DIARY_LENGTH = 200

    # 健康饮水基线：2000 毫升
    # 依据：世界卫生组织及多数膳食指南建议成年人每日饮水量约为 2000 毫升。
    HEALTHY_WATER_ML = 2000

    # 饮水预警下限：1000 毫升
    # 依据：低于 1000 毫升通常意味着明显脱水风险，需明确区分“偏少”与“危险”。
    WARNING_WATER_ML = 1000

    # ------------------------------------------------------------------
    # 功能 1：记账助手 - 收支限额检查
    # ------------------------------------------------------------------
    def check_transaction(self, amount: float) -> bool:
        """
        校验单笔交易金额是否处于安全区间。

        :param amount: 单笔交易金额，正数代表收入，负数代表支出。
        :return: True 表示金额正常；False 表示触发大额异常，需要二次确认。
        """
        # 为什么先判断支出分支：
        #   业务约定“负数代表支出”，单笔支出超过 5000 元（即 amount < -5000）
        #   属于资金风险点，需立即拦截以避免误操作或盗刷损失。
        if amount < -self.MAX_SINGLE_EXPENSE:
            return False

        # 为什么单独判断收入分支：
        #   单笔收入超过 10000 元在个人记账场景中属于非常规事件，
        #   错记会显著影响月度/年度统计，必须让用户二次确认。
        if amount > self.MAX_SINGLE_INCOME:
            return False

        # 为什么默认返回 True：
        #   在两个上限之间的金额属于常规收支，无需打扰用户，
        #   保持“最小提示”原则，提升记账效率。
        return True

    # ------------------------------------------------------------------
    # 功能 2：记录生活 - 日记字数规范
    # ------------------------------------------------------------------
    def validate_diary(self, content: str) -> bool:
        """
        校验日记内容长度是否符合规范。

        :param content: 日记原始字符串内容。
        :return: True 表示字数合规；False 表示太短或太长。
        """
        # 为什么先做 strip 再计算长度：
        #   用户输入常携带首尾空格或换行（尤其在移动端键盘），
        #   若不去除会导致“看似有内容、实则为空白”的误判，影响测试可预期性。
        trimmed_content = content.strip()
        content_length = len(trimmed_content)

        # 为什么使用闭区间 [MIN, MAX] 判断：
        #   产品规范明确“含边界”，使用 <= 与 >= 可以精确覆盖边界值，
        #   避免出现“正好 10 字 / 正好 200 字”被误判为不合规的情况，
        #   同时也方便测试套件直接构造边界用例进行断言。
        if self.MIN_DIARY_LENGTH <= content_length <= self.MAX_DIARY_LENGTH:
            return True

        # 为什么不区分“太短”和“太长”分别返回：
        #   本方法职责单一，只负责“是否合规”的布尔判断，
        #   具体提示文案应由上层 UI 层根据返回值组合决定，保持低耦合。
        return False

    # ------------------------------------------------------------------
    # 功能 3：健康助手 - 每日饮水量评标
    # ------------------------------------------------------------------
    def evaluate_water_intake(self, water_ml: int) -> str:
        """
        根据每日饮水量给出健康评级。

        :param water_ml: 每日饮水量，单位毫升。
        :return: "Invalid" / "Healthy" / "Warning" / "Danger" 之一。
        """
        # 为什么最先拦截负数：
        #   饮水量在物理意义上不存在负值，若不优先拦截，
        #   后续区间比较会得出语义错误的结论（例如 -100 会被归为 "Danger"），
        #   单独返回 "Invalid" 可以让上层准确识别为“数据非法”而非“健康危险”。
        if water_ml < 0:
            return "Invalid"

        # 为什么 >= 2000 判定为 Healthy：
        #   2000 毫升是公认的每日基础需水量，达到该值意味着满足基础代谢需求，
        #   使用 >= 保证“恰好 2000”也被认可为健康，符合用户直觉。
        if water_ml >= self.HEALTHY_WATER_ML:
            return "Healthy"

        # 为什么 1000 <= x < 2000 判定为 Warning：
        #   此区间饮水量未达到推荐值但尚未触及严重缺水线，
        #   属于“需要提醒但无须告警”的中间态，给用户一个改善空间。
        if water_ml >= self.WARNING_WATER_ML:
            return "Warning"

        # 为什么 < 1000 判定为 Danger：
        #   低于 1000 毫升时，人体可能出现明显脱水症状（口渴、尿少、乏力），
        #   需要以最高优先级提醒用户立即补水，因此使用最严重的等级。
        return "Danger"
